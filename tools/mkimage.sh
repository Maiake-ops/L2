#!/bin/sh
# mkimage.sh - build a bootable L2 disk image WITHOUT root (QEMU / CI).
#
# Mirrors `l2install disk`: GPT (1 MiB BIOS boot + ESP + ext4 root), Limine for
# BIOS and UEFI, root mounted by PARTUUID.  It reuses the real installer's
# payload (`l2install dir`) and the same config/limine-installed.conf, but
# populates the filesystems with `mkfs.ext4 -d` and mtools instead of loop
# mounts, so no root is required.  File ownership stays as the build user
# (root can read it all); the real installer chowns to 0:0 when run as root.
#
#   tools/mkimage.sh [out.img] [SIZE_MB]
#   ESP_MB=128 WITH_WIFI=0 WITH_SSL=0 tools/mkimage.sh
#
# Then boot it:
#   qemu-system-x86_64 -m 256 -drive file=out.img,format=raw -nographic
set -eu

SELF_DIR=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
L2_ROOT=$(CDPATH= cd -- "$SELF_DIR/.." && pwd)
OUT=${1:-$L2_ROOT/build/out/l2-installed.img}
SIZE_MB=${2:-256}
ESP_MB=${ESP_MB:-128}
WITH_WIFI=${WITH_WIFI:-0}
WITH_SSL=${WITH_SSL:-0}
ROOT_PARTUUID=${ROOT_PARTUUID:-12345678-1234-4234-8234-123456789abc}

out_dir=$L2_ROOT/build/out
lim=$out_dir/limine/share/limine
limbin=$out_dir/limine/bin/limine
for f in "$out_dir/vmlinuz-l2" "$out_dir/initramfs-l2" "$limbin" \
         "$lim/limine-bios.sys" "$lim/BOOTX64.EFI"; do
    [ -e "$f" ] || { echo "missing $f (run: l2 build all)" >&2; exit 1; }
done
for t in sgdisk mkfs.ext4 mkfs.fat mcopy dd truncate; do
    command -v "$t" >/dev/null 2>&1 || { echo "missing tool: $t" >&2; exit 1; }
done

work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
staging=$work/root
espdir=$work/esp

# 1. Root payload via the real installer (no bootloader, no root needed).
wifi_flag=--no-wifi; [ "$WITH_WIFI" = 1 ] && wifi_flag=
ssl_flag=--no-ssl;   [ "$WITH_SSL" = 1 ] && ssl_flag=
# shellcheck disable=SC2086
"$L2_ROOT/l2install" $wifi_flag $ssl_flag dir "$staging" >/dev/null
# kernel/initramfs live on the ESP; do not also keep them under the root /boot
rm -f "$staging/boot/vmlinuz" "$staging/boot/initramfs"

# fstab (root by PARTUUID; ESP mounted at /boot/efi)
esp_partuuid=12345678-1234-4234-8234-123456789abd
mkdir -p "$staging/etc"
{
    printf '# /etc/fstab - generated by tools/mkimage.sh\n'
    printf 'PARTUUID=%s / ext4 rw,relatime 0 1\n' "$ROOT_PARTUUID"
    printf 'PARTUUID=%s /boot/efi vfat umask=0077 0 2\n' "$esp_partuuid"
} > "$staging/etc/fstab"

# 2. ESP contents: kernel + rescue initramfs + Limine (BIOS + UEFI).
cmd=$(tr -d '\n' < "$L2_ROOT/config/cmdline")
mkdir -p "$espdir/boot/limine" "$espdir/EFI/BOOT"
install -m 0644 "$out_dir/vmlinuz-l2" "$espdir/boot/vmlinuz"
install -m 0644 "$out_dir/initramfs-l2" "$espdir/boot/initramfs"
install -m 0644 "$lim/limine-bios.sys" "$espdir/boot/limine/limine-bios.sys"
install -m 0644 "$lim/BOOTX64.EFI" "$espdir/EFI/BOOT/BOOTX64.EFI"
sed -e "s/@ROOT_PARTUUID@/$ROOT_PARTUUID/g" -e "s|@CMDLINE@|$cmd|g" \
    "$L2_ROOT/config/limine-installed.conf" > "$espdir/boot/limine/limine.conf"
cp "$espdir/boot/limine/limine.conf" "$espdir/EFI/BOOT/limine.conf"

# 3. Partition a fresh image (GPT).  sgdisk writes both primary and backup GPT
#    (sfdisk on a regular file skips the backup, which Limine then rejects).
truncate -s "${SIZE_MB}M" "$OUT"
esp_sectors=$((ESP_MB * 2048))
root_start=$((4096 + esp_sectors))
sgdisk --zap-all "$OUT" >/dev/null 2>&1
sgdisk -n 1:2048:4095 -t 1:ef02 -c 1:L2-BIOS "$OUT" >/dev/null 2>&1
sgdisk -n 2:4096:$((root_start - 1)) -t 2:ef00 -c 2:L2-ESP -u 2:"$esp_partuuid" "$OUT" >/dev/null 2>&1
sgdisk -n 3:"$root_start":0 -t 3:8300 -c 3:L2-root -u 3:"$ROOT_PARTUUID" "$OUT" >/dev/null 2>&1

# 4. ext4 root, populated from the staging dir (no mount needed).  Match the
#    installer: no journal, no reserved blocks, few inodes -> minimal overhead.
#    Stop 34 sectors short of the disk end so the backup GPT is not overwritten.
total_sectors=$((SIZE_MB * 2048))
root_bytes=$(( (total_sectors - 34 - root_start) * 512 ))
mkfs.ext4 -q -F -b 4096 -O ^has_journal -m 0 -N 8192 -L L2 \
    -E offset=$((root_start * 512)) -d "$staging" "$OUT" $((root_bytes / 4096))

# 5. FAT32 ESP: build it as a standalone file, then copy it into place.
truncate -s "${ESP_MB}M" "$work/esp.img"
mkfs.fat -F32 -n L2ESP "$work/esp.img" >/dev/null
mcopy -s -i "$work/esp.img" "$espdir/boot" "$espdir/EFI" ::
dd if="$work/esp.img" of="$OUT" bs=512 seek=4096 conv=notrunc status=none

# 6. Limine BIOS boot sector (stage 2 in partition 1).
"$limbin" bios-install "$OUT" 1

echo "image: $OUT ($(du -h "$OUT" | cut -f1))"
echo "boot:  qemu-system-x86_64 -m 256 -drive file=$OUT,format=raw -nographic"
echo "UEFI:  qemu-system-x86_64 -m 256 -drive file=$OUT,format=raw -nographic \\"
echo "         -drive if=pflash,format=raw,readonly=on,file=\$(OVMF_CODE.fd)"